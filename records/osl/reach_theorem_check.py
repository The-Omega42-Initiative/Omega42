import itertools, sys
import numpy as np
R = []
def ok(name, c): R.append(bool(c)); print(('PASS ' if c else 'FAIL ') + name)

# finite ingredients of the proof
def mul(X, Y, q): return [[(X[0][0]*Y[0][0]+X[0][1]*Y[1][0]) % q, (X[0][0]*Y[0][1]+X[0][1]*Y[1][1]) % q],
                          [(X[1][0]*Y[0][0]+X[1][1]*Y[1][0]) % q, (X[1][0]*Y[0][1]+X[1][1]*Y[1][1]) % q]]
def pw(X, n, q):
    P = [[1, 0], [0, 1]]
    for _ in range(n): P = mul(P, X, q)
    return P
A = [[0, 1], [1, 1]]; E21 = [[0, 0], [1, 0]]
conj = [mul(mul(pw(A, (8 - j) % 8, 3), E21, 3), pw(A, j, 3), 3) for j in range(8)]
def rank3(rows):
    rows = [r[:] for r in rows]; r = 0
    for c in range(4):
        p = next((i for i in range(r, len(rows)) if rows[i][c] % 3), None)
        if p is None: continue
        rows[r], rows[p] = rows[p], rows[r]; inv = 1 if rows[r][c] % 3 == 1 else 2; rows[r] = [x * inv % 3 for x in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] % 3: f = rows[i][c]; rows[i] = [(x - f * y) % 3 for x, y in zip(rows[i], rows[r])]
        r += 1
    return r
ok('the conjugates A^-j E21 A^j mod 3 have trace 0 and span a space of dimension 3 = dim sl_2(F_3)',
   all((C[0][0] + C[1][1]) % 3 == 0 for C in conj) and rank3([sum(C, []) for C in conj]) == 3)
ok('A mod 3 has order 8 and is transitive on the 8 nonzero vectors of F_3^2', pw(A, 8, 3) == [[1, 0], [0, 1]] and pw(A, 4, 3) != [[1, 0], [0, 1]]
   and len({tuple(pw(A, j, 3)[0]) for j in range(8)}) == 8)
A8 = pw(A, 8, 9); M = [[((A8[i][j] - (i == j)) // 3) % 3 for j in range(2)] for i in range(2)]
ok('A^8 = I + 3M mod 9 with M = %s non-scalar mod 3' % M, all((A8[i][j] - (i == j)) % 3 == 0 for i in range(2) for j in range(2)) and not (M[0][1] == 0 and M[1][0] == 0 and M[0][0] == M[1][1]))
ok('X -> Xv maps sl_2(F_3) onto F_3^2 for each nonzero v', all(len({((x*v0 + y*v1) % 3, (z*v0 - x*v1) % 3) for x in range(3) for y in range(3) for z in range(3)}) == 9
                                                              for v0 in range(3) for v1 in range(3) if (v0, v1) != (0, 0)))
ok('cubing raises the level: (I + 3^m Y)^3 = I + 3^(m+1) Y mod 3^(m+2), all Y mod 3, m = 1, 2, 3',
   all(pw([[1 + 3**m * y0, 3**m * y1], [3**m * y2, 1 + 3**m * y3]], 3, 3**(m+2)) ==
       [[(1 + 3**(m+1) * y0) % 3**(m+2), 3**(m+1) * y1 % 3**(m+2)], [3**(m+1) * y2 % 3**(m+2), (1 + 3**(m+1) * y3) % 3**(m+2)]]
       for m in (1, 2, 3) for y0 in range(3) for y1 in range(3) for y2 in range(3) for y3 in range(3)))

# the reach table, k = 1 .. 7
def reach(ops, k):
    q = 3**k; n = q*q
    dist = np.full(n, -1, dtype=np.int16); s = (2 % q)*q + 5 % q; dist[s] = 0; fr = np.array([s]); d = 0
    while fr.size:
        a = fr // q; b = fr % q; nxt = []
        for o in ops:
            nxt.append({'A': lambda: b*q + (a + b) % q, 'V': lambda: (2*a % q)*q + 2*b % q,
                        'C': lambda: (3*a % q)*q + 3*b % q, 'S': lambda: a*q + (3*a + b) % q}[o]())
        y = np.unique(np.concatenate(nxt)); y = y[dist[y] < 0]; d += 1; dist[y] = d; fr = y
    return int((dist >= 0).sum()), int(dist.max())
subsets = [''.join(c) for r in range(1, 5) for c in itertools.combinations('AVCS', r)]
for k in range(1, 8):
    full = sorted(o for o in subsets if reach(o, k)[0] == 9**k)
    want = ['AC', 'ACS', 'AVC', 'AVCS'] if k == 1 else ['ACS', 'AVC', 'AVCS']
    prim = [o for o in subsets if 'C' not in o]
    ok('k=%d: the subsets reaching all %d states are exactly %s; without C at most the %d primitive states' % (k, 9**k, want, 8 * 9**(k-1)),
       full == want and all(reach(o, k)[0] <= 8 * 9**(k-1) for o in prim))
    dv, ds = reach('AVC', k)[1], reach('ACS', k)[1]
    ok('k=%d: diameters {A,V,C} = %d (2*3^k - 2 = %d), {A,C,S} = %d' % (k, dv, 2*3**k - 2, ds), dv == 2*3**k - 2 and ds == [7, 10, 12, 16, 20, 23, 26][k-1])
print('%d of %d checks PASS' % (sum(R), len(R)))
sys.exit(0 if all(R) else 1)
